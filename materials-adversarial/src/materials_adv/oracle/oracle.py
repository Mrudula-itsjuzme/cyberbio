class ExternalDFTOracle(PhysicalPropertyOracle):
    """Placeholder DFT oracle backed by Quantum ESPRESSO via HPC queue.

    This is a scaffold for future integration. All methods raise
    NotImplementedError until a working backend is connected.

    See docs/ORACLE_BACKEND_CONTRACT.md and docs/HPC_ORACLE_EXECUTION_GUIDE.md
    for the full execution protocol.
    """

    def __init__(
        self,
        input_dir: str | Path,
        output_dir: str | Path,
        queue_system: str = "slurm",
        qe_version: str = "unknown",
    ) -> None:
        self.input_dir = Path(input_dir)
        self.output_dir = Path(output_dir)
        self.queue_system = queue_system
        self.qe_version = qe_version
        log.warning(
            "ExternalDFTOracle is a placeholder — DFT compute is not implemented. "
            "Connect a working Quantum ESPRESSO backend before using in production."
        )

    def prepare(self, candidate_smiles: str, source_smiles: str | None = None) -> OracleJob:
        # Basic RDKit validation
        try:
            from rdkit import Chem
            mol = Chem.MolFromSmiles(candidate_smiles)
            if mol is None:
                raise ValueError(f"RDKit cannot parse SMILES: {candidate_smiles!r}")
        except ImportError:
            pass  # Can't validate without RDKit but don't fail the scaffold

        import uuid
        job_id = f"dft_{uuid.uuid4().hex[:8]}"
        return OracleJob(
            job_id=job_id,
            candidate_smiles=candidate_smiles,
            status=OracleStatus.PENDING,
            metadata={"source_smiles": source_smiles, "method": "DFT/QE"},
        )

    def evaluate(self, job: OracleJob) -> OracleJob:
        raise NotImplementedError(
            "ExternalDFTOracle.evaluate() is not implemented. "
            "A working Quantum ESPRESSO HPC backend must be connected first. "
            "See docs/HPC_ORACLE_EXECUTION_GUIDE.md for protocol."
        )

    def status(self, job: OracleJob) -> OracleStatus:
        raise NotImplementedError("ExternalDFTOracle.status() is not implemented.")

    def collect(self, job: OracleJob) -> OracleResult:
        raise NotImplementedError("ExternalDFTOracle.collect() is not implemented.")


class CachedLookupOracle(PhysicalPropertyOracle):
    """Oracle backed by a pre-computed property database (cached lookup).

    Useful for evaluating candidates whose properties were previously computed
    by DFT or other methods and stored in a JSON/CSV lookup table.

    Returns UNSUPPORTED status for candidates not found in the cache.
    """

    def __init__(self, cache_path: str | Path, property_name: str = "bandgap_eV") -> None:
        self.cache_path = Path(cache_path)
        self.property_name = property_name
        self._cache: dict[str, float] = {}
        self._load_cache()

    def _load_cache(self) -> None:
        if not self.cache_path.exists():
            log.warning(f"Cache file not found: {self.cache_path}. Returning empty cache.")
            return
        with open(self.cache_path) as f:
            data = json.load(f)
        # Expected format: {"smiles_string": property_value, ...}
        # or a list of {"smiles": ..., "property_name": value}
        if isinstance(data, dict):
            self._cache = data
        elif isinstance(data, list):
            for record in data:
                smi = record.get("smiles") or record.get("SMILES")
                val = record.get(self.property_name)
                if smi and val is not None:
                    self._cache[smi] = float(val)
        log.info(f"Loaded {len(self._cache)} cached property values from {self.cache_path}")

    def _canonicalize(self, smiles: str) -> str | None:
        try:
            from rdkit import Chem
            mol = Chem.MolFromSmiles(smiles)
            if mol:
                return Chem.MolToSmiles(mol, canonical=True)
        except ImportError:
            pass
        return smiles

    def prepare(self, candidate_smiles: str, source_smiles: str | None = None) -> OracleJob:
        import uuid
        job_id = f"cached_{uuid.uuid4().hex[:8]}"
        can = self._canonicalize(candidate_smiles)
        in_cache = can in self._cache or candidate_smiles in self._cache
        return OracleJob(
            job_id=job_id,
            candidate_smiles=candidate_smiles,
            status=OracleStatus.PENDING if in_cache else OracleStatus.UNSUPPORTED,
            metadata={"source_smiles": source_smiles, "canonical": can, "in_cache": in_cache},
        )

    def evaluate(self, job: OracleJob) -> OracleJob:
        if job.status == OracleStatus.UNSUPPORTED:
            return job
        job.status = OracleStatus.COMPLETED
        return job

    def status(self, job: OracleJob) -> OracleStatus:
        return job.status

    def collect(self, job: OracleJob) -> OracleResult:
        if job.status not in (OracleStatus.COMPLETED, OracleStatus.CACHED):
            raise RuntimeError(f"Job {job.job_id} is not COMPLETED (status={job.status})")
        can = job.metadata.get("canonical", job.candidate_smiles)
        value = self._cache.get(can) or self._cache.get(job.candidate_smiles)
        return OracleResult(
            job=job,
            property_value=value,
            property_units="eV",
            uncertainty=None,
            method="cached_lookup",
            raw_output_path=str(self.cache_path),
        )

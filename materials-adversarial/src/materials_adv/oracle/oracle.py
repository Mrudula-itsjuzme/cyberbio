"""Physical Property Oracle interface.

Defines the abstract contract for an external oracle that can independently
compute bandgap (or other physical properties) for candidate structures
without relying on the surrogate model being attacked.

KEY SCIENTIFIC REQUIREMENT
--------------------------
Chemistry-changing adversarial candidates generated by substitution, insertion,
deletion, rearrangement, or Metropolis-style stochastic search have *unknown*
physical properties. Without an independent oracle, we can only measure
*model sensitivity* (drift in model prediction), NOT *physical inaccuracy*
(error relative to true Eg).

This interface scaffolds integration with:
  - DFT calculations via Quantum ESPRESSO (external HPC queue)
  - Validated property databases (cached lookup)

USAGE
-----
This module is OPTIONAL and is never imported automatically in normal
experiment pipelines. Only import it when explicitly setting up oracle-backed
evaluation.

IMPLEMENTATION STATUS
---------------------
- ExternalDFTOracle: placeholder — interface defined, compute not implemented
- CachedLookupOracle: placeholder — interface defined, lookup not implemented
See docs/ORACLE_BACKEND_CONTRACT.md for the full specification.
"""

from __future__ import annotations

import abc
import json
import logging
from dataclasses import dataclass, field
from enum import Enum, auto
from pathlib import Path
from typing import Any

log = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Status types
# ---------------------------------------------------------------------------

class OracleStatus(Enum):
    PENDING = auto()       # Job submitted, not yet started
    RUNNING = auto()       # Job is executing
    COMPLETED = auto()     # Job finished, result available
    FAILED = auto()        # Job failed, no result
    CACHED = auto()        # Result loaded from cache/database
    UNSUPPORTED = auto()   # SMILES not supported by this oracle backend


@dataclass
class OracleJob:
    """Handle for a submitted oracle computation."""
    job_id: str
    candidate_smiles: str
    status: OracleStatus = OracleStatus.PENDING
    metadata: dict[str, Any] = field(default_factory=dict)


@dataclass
class OracleResult:
    """Result from a completed oracle computation."""
    job: OracleJob
    property_value: float | None       # Physical property value (e.g. Eg in eV)
    property_units: str | None         # Units (e.g. "eV")
    uncertainty: float | None          # Estimated uncertainty if available
    method: str | None                 # Computational method used (e.g. "DFT/PBE/QE")
    raw_output_path: str | None        # Path to raw output files
    valid: bool = False                # True if result passed all validation checks
    validation_notes: list[str] = field(default_factory=list)


# ---------------------------------------------------------------------------
# Abstract interface
# ---------------------------------------------------------------------------

class PhysicalPropertyOracle(abc.ABC):
    """Abstract base class for physical property oracles.

    All oracle implementations must follow this contract so they can be
    substituted transparently in oracle-backed evaluation pipelines.

    The contract has five stages:

    1. ``prepare`` — Validate and pre-process a candidate. Returns a job
       handle (OracleJob) or raises ValueError for unsupported structures.

    2. ``evaluate`` — Submit the job to the oracle backend (e.g. write QE
       input files and submit to HPC queue). Returns the submitted OracleJob.

    3. ``status`` — Non-blocking poll for the job's current status.

    4. ``collect`` — Retrieve and parse the result once status is COMPLETED.
       Returns an OracleResult.

    5. ``validate_result`` — Apply sanity checks to a result. Returns the
       result with ``valid`` set and ``validation_notes`` populated.
    """

    @abc.abstractmethod
    def prepare(self, candidate_smiles: str, source_smiles: str | None = None) -> OracleJob:
        """Validate the candidate and create a job handle.

        Parameters
        ----------
        candidate_smiles:
            PSMILES string of the candidate structure. Must be RDKit-parseable.
        source_smiles:
            The original molecule this candidate was derived from (for provenance).

        Returns
        -------
        OracleJob
            A job handle with status=PENDING.

        Raises
        ------
        ValueError
            If the candidate is not supported (e.g. invalid SMILES, too large).
        """
        ...

    @abc.abstractmethod
    def evaluate(self, job: OracleJob) -> OracleJob:
        """Submit the job to the oracle backend.

        Parameters
        ----------
        job:
            Job handle from ``prepare``.

        Returns
        -------
        OracleJob
            Updated handle with status=RUNNING or FAILED.
        """
        ...

    @abc.abstractmethod
    def status(self, job: OracleJob) -> OracleStatus:
        """Poll job status without blocking.

        Returns
        -------
        OracleStatus
            Current status.
        """
        ...

    @abc.abstractmethod
    def collect(self, job: OracleJob) -> OracleResult:
        """Retrieve and parse the result for a completed job.

        Parameters
        ----------
        job:
            Job handle that should have status=COMPLETED.

        Returns
        -------
        OracleResult
            Parsed result (not yet validated — call ``validate_result`` next).

        Raises
        ------
        RuntimeError
            If job is not yet COMPLETED.
        """
        ...

    def validate_result(self, result: OracleResult) -> OracleResult:
        """Apply sanity checks to an oracle result.

        Default implementation enforces:
        - property_value must be a finite float
        - property_value within physically plausible range for Eg (0 to 15 eV)
        - uncertainty (if given) must be non-negative

        Subclasses should override to add backend-specific checks.
        """
        notes: list[str] = []
        valid = True

        if result.property_value is None:
            notes.append("property_value is None — no result returned")
            valid = False
        elif not (isinstance(result.property_value, (int, float)) and
                  result.property_value == result.property_value):  # NaN check
            notes.append(f"property_value is not finite: {result.property_value}")
            valid = False
        else:
            # Physical plausibility: Eg for polymers is typically 0–15 eV
            if not (0.0 <= result.property_value <= 15.0):
                notes.append(
                    f"property_value {result.property_value:.3f} eV is outside "
                    "physically plausible range [0, 15] eV for polymer bandgap"
                )
                valid = False

        if result.uncertainty is not None and result.uncertainty < 0:
            notes.append(f"uncertainty {result.uncertainty} is negative")
            valid = False

        result.valid = valid
        result.validation_notes = notes
        return result


